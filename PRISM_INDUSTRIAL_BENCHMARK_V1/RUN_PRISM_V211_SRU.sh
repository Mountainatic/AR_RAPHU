OUTPUT="${PRISM_V211_OUTPUT:-$PROJECT/results_prism_v2_1_1_sru}"

export AR_RAPHU_RUNTIME_MANAGER=uv
export PRISM_V211_WORKERS="${PRISM_V211_WORKERS:-8}"
export PRISM_V211_THREADS_PER_WORKER="${PRISM_V211_THREADS_PER_WORKER:-4}"
export PRISM_V211_MEMORY_GIB_PER_WORKER="${PRISM_V211_MEMORY_GIB_PER_WORKER:-4}"
