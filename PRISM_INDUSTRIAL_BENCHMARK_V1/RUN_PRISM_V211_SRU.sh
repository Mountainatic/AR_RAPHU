exec "$UV" run --project "$UV_PROJECT" python \
  "$PROJECT/scripts/run_prism_v211_chain.py" \
  --project "$PROJECT" \
  --shared "$SHARED" \
  --baseline-source "$BASELINE_SOURCE" \
  --output "$OUTPUT" \
  "$@"
